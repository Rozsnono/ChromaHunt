/** Zod schemas for API request bodies shared by the backend and the clients. */
import { z } from 'zod';
import { PERMISSIONS } from './constants';
import { isDateString, isValidTimeZone } from './time';

export const emailSchema = z.email().max(254).transform((v) => v.trim().toLowerCase());
export const passwordSchema = z.string().min(10, 'PASSWORD_TOO_SHORT').max(128);
export const hexColorSchema = z
  .string()
  .regex(/^#[0-9a-fA-F]{6}$/, 'INVALID_HEX')
  .transform((v) => v.toLowerCase());
export const localeSchema = z.enum(['hu', 'en']);
export const objectIdSchema = z.string().regex(/^[0-9a-fA-F]{24}$/, 'INVALID_ID');
export const timeOfDaySchema = z.string().regex(/^([01]\d|2[0-3]):[0-5]\d$/, 'INVALID_TIME');
export const timeZoneSchema = z.string().refine(isValidTimeZone, 'INVALID_TIMEZONE');
export const deviceIdSchema = z.string().min(8).max(128);
export const dateStringSchema = z.string().refine(isDateString, 'INVALID_DATE');
export const permissionSchema = z.enum(PERMISSIONS);

/** Partial group settings (a group stores only the fields it overrides). */
export const groupSettingsPatchSchema = z
  .object({
    requiredPhotosPerDay: z.number().int().min(1).max(10),
    dailyDrawTime: timeOfDaySchema,
    timezone: timeZoneSchema,
    deadlineHours: z.number().int().min(1).max(24),
    retentionDays: z.number().int().min(1).max(365),
    scoringEnabled: z.boolean(),
    colorCooldownDays: z.number().int().min(0).max(30),
    acceptanceThreshold: z.number().int().min(0).max(100),
    missingPhotoPenalty: z.number().int().min(0).max(100),
    minDailyPoints: z.number().int().min(-100).max(0),
    deadlineReminderHours: z.number().int().min(0).max(12),
    notifyDailyColor: z.boolean(),
    notifyDeadline: z.boolean(),
  })
  .partial()
  .strict();
export type GroupSettingsPatch = z.infer<typeof groupSettingsPatchSchema>;

export const globalSettingsSchema = z
  .object({
    defaults: groupSettingsPatchSchema,
    minAcceptanceThreshold: z.number().int().min(0).max(100),
    maxRetentionDays: z.number().int().min(1).max(3650),
    storageQuotaBytes: z.number().int().min(0),
    registrationOpen: z.boolean(),
  })
  .partial()
  .strict();

export const registerSchema = z.object({
  email: emailSchema,
  password: passwordSchema,
  displayName: z.string().trim().min(2).max(40),
  locale: localeSchema.default('hu'),
  deviceId: deviceIdSchema,
  acceptedPrivacy: z.literal(true),
  privacyPolicyVersion: z.string().min(1).max(32),
});

export const loginSchema = z.object({
  email: emailSchema,
  password: z.string().min(1).max(128),
  deviceId: deviceIdSchema,
});

export const refreshSchema = z.object({
  refreshToken: z.string().min(20).max(256),
  deviceId: deviceIdSchema,
});

export const logoutSchema = z.object({
  refreshToken: z.string().min(20).max(256),
  deviceId: deviceIdSchema.optional(),
});

export const changePasswordSchema = z.object({
  currentPassword: z.string().min(1).max(128),
  newPassword: passwordSchema,
  deviceId: deviceIdSchema,
});

export const biometricEnrollSchema = z.object({
  deviceId: deviceIdSchema,
  /** Random per-device secret generated by the app (>= 32 chars of entropy). */
  secret: z.string().min(32).max(256),
});

export const biometricLoginSchema = z.object({
  deviceId: deviceIdSchema,
  secret: z.string().min(32).max(256),
});

export const profileUpdateSchema = z
  .object({ displayName: z.string().trim().min(2).max(40), locale: localeSchema })
  .partial()
  .strict();

export const deleteAccountSchema = z.object({ password: z.string().min(1).max(128) });

export const acceptTermsSchema = z.object({ privacyPolicyVersion: z.string().min(1).max(32) });

export const pushTokenSchema = z.object({
  token: z.string().min(10).max(256),
  deviceId: deviceIdSchema,
});

export const createGroupSchema = z.object({
  name: z.string().trim().min(2).max(60),
  settings: groupSettingsPatchSchema.optional(),
});

export const joinGroupSchema = z.object({
  code: z
    .string()
    .trim()
    .min(6)
    .max(64)
    .transform((v) => v.toUpperCase().replace(/[\s-]/g, '')),
});

export const joinDecisionSchema = z.object({ decision: z.enum(['approve', 'reject']) });

export const uploadIntentSchema = z.object({
  idempotencyKey: z.string().min(16).max(64),
  sizeBytes: z.number().int().min(1),
  contentType: z.literal('image/jpeg'),
  capturedAt: z.iso.datetime(),
  /** UX-only value computed by the app. It is stored but never trusted. */
  clientColorScore: z.number().min(0).max(100).optional(),
  clientSha256: z.string().regex(/^[0-9a-f]{64}$/).optional(),
});

export const calendarQuerySchema = z.object({
  from: dateStringSchema,
  to: dateStringSchema,
});

export const rankingQuerySchema = z.object({
  week: z.string().regex(/^\d{4}-W\d{2}$/).optional(),
});

export const paletteColorSchema = z.object({
  name: z.string().trim().min(1).max(40),
  hex: hexColorSchema,
  isActive: z.boolean().default(true),
});

export const adminLoginSchema = z.object({ password: z.string().min(1).max(256) });

export const adminUserPatchSchema = z
  .object({ isDisabled: z.boolean(), displayName: z.string().trim().min(2).max(40) })
  .partial()
  .strict();

export const adminPermissionsSchema = z.object({ permissions: z.array(permissionSchema).max(PERMISSIONS.length) });

export const adminReassignSchema = z.object({ userId: objectIdSchema });
